/**
 * 周期性条目自动任务生成器
 *
 * 根据用户在引导页勾选的周期条目，自动生成对应频率的待办任务。
 * - daily：每天生成一条，plannedDate=当天
 * - weekly：每周一生成一条，plannedDate=本周一（本周内完成）
 * - monthly：每月1号生成一条，plannedDate=本月1号
 * - yearly：每年1月1日（或按季度节点）生成一条
 *
 * 防重复：同一 [recurringCatalogId + recurringAnchor] 只生成一条。
 * 下一周期到来时锚点变化，自动新建。
 */
import { db, type Task, type TaskPriority, type RecurringFrequency } from "@/storage/db";
import { createTask } from "@/storage/repositories/taskRepo";
import { getSetting, setSetting } from "@/storage/repositories/settingsRepo";
import { findCatalogItem, type CatalogItem, type CatalogFrequency } from "@/domain/recurringCatalog";
import { todayKey } from "@/lib/date";

/* ===== 设置读写 ===== */

const SEL_KEY = "userSelectedRecurring";
const ONBOARD_KEY = "onboardingCompleted";

export async function getSelectedRecurring(): Promise<string[]> {
  return getSetting<string[]>(SEL_KEY, []);
}

export async function setSelectedRecurring(ids: string[]): Promise<void> {
  await setSetting(SEL_KEY, ids);
}

export async function isOnboardingCompleted(): Promise<boolean> {
  return getSetting<boolean>(ONBOARD_KEY, false);
}

export async function setOnboardingCompleted(v = true): Promise<void> {
  await setSetting(ONBOARD_KEY, v);
}

/* ===== 锚点计算 ===== */

/** 本周一的 YYYY-MM-DD（周一起始） */
function weekStartKey(d: Date): string {
  const x = new Date(d);
  const day = x.getDay(); // 0=周日
  const diff = day === 0 ? -6 : 1 - day; // 回到周一
  x.setDate(x.getDate() + diff);
  return toDateKey(x);
}

/** 本月1号的 YYYY-MM-DD */
function monthStartKey(d: Date): string {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-01`;
}

/** 今年1月1日的 YYYY-MM-DD */
function yearStartKey(d: Date): string {
  return `${d.getFullYear()}-01-01`;
}

function toDateKey(d: Date): string {
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, "0")}-${String(d.getDate()).padStart(2, "0")}`;
}

/** 当前周期的锚点 */
function currentAnchor(freq: CatalogFrequency, now = new Date()): string {
  switch (freq) {
    case "daily": return todayKey();
    case "weekly": return weekStartKey(now);
    case "monthly": return monthStartKey(now);
    case "yearly": return yearStartKey(now);
  }
}

/** yearly 按季度节点的 plannedDate（如 year-q2 → 今年4月1日） */
function yearlyPlannedDate(node: string, now = new Date()): string {
  const y = now.getFullYear();
  if (node === "year-q1") return `${y}-01-01`;
  if (node === "year-q2") return `${y}-04-01`;
  if (node === "year-q3") return `${y}-07-01`;
  if (node === "year-q4") return `${y}-10-01`;
  if (node === "year-h1") return `${y}-04-01`;
  if (node === "year-end") return `${y}-10-01`;
  return `${y}-01-01`;
}

/** catalog 优先级 → 任务优先级 */
function mapPriority(p: CatalogItem["priority"]): TaskPriority {
  if (p === "high") return "high";
  if (p === "medium") return "medium";
  return "low";
}

/* ===== 核心生成 ===== */

export interface EnsureResult {
  created: number;
  skipped: number;
  createdItems: CatalogItem[];
}

/**
 * 检查并生成当前各周期应有的自动任务。
 * 幂等：同锚点已存在则跳过。
 */
export async function ensureRecurringTasksForToday(now = new Date()): Promise<EnsureResult> {
  const selected = await getSelectedRecurring();
  if (selected.length === 0) return { created: 0, skipped: 0, createdItems: [] };

  const createdItems: CatalogItem[] = [];
  let created = 0;
  let skipped = 0;

  for (const entryId of selected) {
    const item = findCatalogItem(entryId);
    if (!item) { skipped++; continue; }

    const anchor = currentAnchor(item.frequency, now);

    // 查同锚点同条目是否已有未删除任务
    const existing = await db.tasks
      .where("[recurringCatalogId+recurringAnchor]")
      .equals([entryId, anchor])
      .filter((t) => !t.deletedAt)
      .first();

    if (existing) { skipped++; continue; }

    // 计算 plannedDate
    let plannedDate: string;
    if (item.frequency === "daily") {
      plannedDate = todayKey();
    } else if (item.frequency === "weekly") {
      plannedDate = weekStartKey(now);
    } else if (item.frequency === "monthly") {
      plannedDate = monthStartKey(now);
    } else {
      plannedDate = yearlyPlannedDate(item.node, now);
    }

    await createTask({
      title: item.actionLabel,
      description: item.plainTalk.slice(0, 200),
      priority: mapPriority(item.priority),
      plannedDate,
      entryId: item.entryId,
      autoGenerated: true,
      recurringCatalogId: item.entryId,
      recurringFrequency: item.frequency as RecurringFrequency,
      recurringAnchor: anchor,
    });

    created++;
    createdItems.push(item);
  }

  return { created, skipped, createdItems };
}

/* ===== 查询（供总览页用） ===== */

/** 今日 daily 自动任务（未完成：todo/doing） */
export async function getTodayAutoTasks(): Promise<Task[]> {
  const today = todayKey();
  return db.tasks
    .where("plannedDate")
    .equals(today)
    .filter(
      (t) =>
        t.autoGenerated &&
        t.recurringFrequency === "daily" &&
        !t.deletedAt &&
        t.status !== "done" &&
        t.status !== "cancelled"
    )
    .toArray();
}

/** 当前周/月/年未完成的自动任务 */
export async function getActivePeriodicAutoTasks(): Promise<Task[]> {
  const now = new Date();
  const wAnchor = weekStartKey(now);
  const mAnchor = monthStartKey(now);
  const yAnchor = yearStartKey(now);
  return db.tasks
    .filter(
      (t) =>
        t.autoGenerated &&
        !t.deletedAt &&
        t.status !== "done" &&
        t.status !== "cancelled" &&
        t.recurringFrequency !== "daily" &&
        t.recurringAnchor !== null &&
        (t.recurringAnchor === wAnchor || t.recurringAnchor === mAnchor || t.recurringAnchor === yAnchor)
    )
    .toArray();
}

/** 今日 daily 自动任务完成率 */
export async function getTodayAutoCompletion(): Promise<{ done: number; total: number }> {
  const today = todayKey();
  const all = await db.tasks
    .where("plannedDate")
    .equals(today)
    .filter((t) => t.autoGenerated && t.recurringFrequency === "daily" && !t.deletedAt && t.status !== "cancelled")
    .toArray();
  const done = all.filter((t) => t.status === "done").length;
  return { done, total: all.length };
}

/** 从勾选列表移除（用户不想再自动生成某条目） */
export async function removeFromRecurring(entryId: string): Promise<void> {
  const sel = await getSelectedRecurring();
  await setSelectedRecurring(sel.filter((id) => id !== entryId));
}

/** 今日是否已执行过 ensure（避免频繁重复生成） */
export async function markEnsureRunToday(): Promise<void> {
  await setSetting("lastEnsureDate", todayKey());
}

export async function isEnsureRunToday(): Promise<boolean> {
  return (await getSetting<string>("lastEnsureDate", "")) === todayKey();
}
