import { describe, it, expect, beforeEach } from "vitest";
import { db } from "@/storage/db";
import {
  setSelectedRecurring,
  getSelectedRecurring,
  setOnboardingCompleted,
  isOnboardingCompleted,
  ensureRecurringTasksForToday,
  getTodayAutoTasks,
  getActivePeriodicAutoTasks,
  removeFromRecurring,
} from "@/domain/autoTask";
import { recurringCatalog } from "@/domain/recurringCatalog";
import { completeTask, getTask } from "@/storage/repositories/taskRepo";
import { todayKey } from "@/lib/date";

const DAILY_ITEMS = recurringCatalog.items.filter((i) => i.frequency === "daily");
const WEEKLY_ITEMS = recurringCatalog.items.filter((i) => i.frequency === "weekly");
const YEARLY_ITEMS = recurringCatalog.items.filter((i) => i.frequency === "yearly");

describe("autoTask 周期任务自动生成", () => {
  beforeEach(async () => {
    await db.delete();
    await db.open();
    await db.bookVersions.bulkPut([]);
  });

  it("catalog 含周期条目（每日/每周/每年）", () => {
    expect(DAILY_ITEMS.length).toBeGreaterThan(10);
    expect(WEEKLY_ITEMS.length).toBeGreaterThan(0);
    expect(YEARLY_ITEMS.length).toBeGreaterThan(5);
  });

  it("未勾选时 ensure 不生成任何任务", async () => {
    const r = await ensureRecurringTasksForToday();
    expect(r.created).toBe(0);
    expect(r.skipped).toBe(0);
  });

  it("勾选 2 条每日条目后 ensure 生成对应任务", async () => {
    const ids = DAILY_ITEMS.slice(0, 2).map((i) => i.entryId);
    await setSelectedRecurring(ids);

    const r = await ensureRecurringTasksForToday();
    expect(r.created).toBe(2);
    expect(r.skipped).toBe(0);

    const tasks = await getTodayAutoTasks();
    expect(tasks.length).toBe(2);
    expect(tasks.every((t) => t.autoGenerated)).toBe(true);
    expect(tasks.every((t) => t.recurringFrequency === "daily")).toBe(true);
    expect(tasks.every((t) => t.plannedDate === todayKey())).toBe(true);
    // 关联原书条目
    expect(tasks.every((t) => t.entryId !== null)).toBe(true);
  });

  it("幂等：同日重复 ensure 不重复生成", async () => {
    const ids = DAILY_ITEMS.slice(0, 1).map((i) => i.entryId);
    await setSelectedRecurring(ids);

    const r1 = await ensureRecurringTasksForToday();
    const r2 = await ensureRecurringTasksForToday();
    expect(r1.created).toBe(1);
    expect(r2.created).toBe(0);
    expect(r2.skipped).toBe(1);

    const tasks = await getTodayAutoTasks();
    expect(tasks.length).toBe(1);
  });

  it("完成任务后今日不再出现，但任务记录保留", async () => {
    const ids = DAILY_ITEMS.slice(0, 1).map((i) => i.entryId);
    await setSelectedRecurring(ids);
    await ensureRecurringTasksForToday();

    const before = await getTodayAutoTasks();
    expect(before.length).toBe(1);
    await completeTask(before[0].id);

    const after = await getTodayAutoTasks();
    expect(after.length).toBe(0); // done 不在未完成列表
    const log = await getTask(before[0].id);
    expect(log?.status).toBe("done");
  });

  it("勾选 yearly 条目生成年度任务，plannedDate 在本年", async () => {
    const item = YEARLY_ITEMS[0];
    await setSelectedRecurring([item.entryId]);
    const r = await ensureRecurringTasksForToday();
    expect(r.created).toBe(1);

    const periodic = await getActivePeriodicAutoTasks();
    expect(periodic.length).toBe(1);
    expect(periodic[0].recurringFrequency).toBe("yearly");
    expect(periodic[0].plannedDate?.startsWith(String(new Date().getFullYear()))).toBe(true);
  });

  it("removeFromRecurring 后 ensure 不再生成该条目", async () => {
    const ids = DAILY_ITEMS.slice(0, 1).map((i) => i.entryId);
    await setSelectedRecurring(ids);
    await ensureRecurringTasksForToday();
    expect((await getTodayAutoTasks()).length).toBe(1);

    await removeFromRecurring(ids[0]);
    expect(await getSelectedRecurring()).toEqual([]);

    // 已生成的今日任务仍在（不删历史），但重新 ensure 不新增
    const r = await ensureRecurringTasksForToday();
    expect(r.created).toBe(0);
  });

  it("onboarding 标志读写", async () => {
    expect(await isOnboardingCompleted()).toBe(false);
    await setOnboardingCompleted(true);
    expect(await isOnboardingCompleted()).toBe(true);
  });

  it("自动任务标题取自 catalog actionLabel", async () => {
    const item = DAILY_ITEMS[0];
    await setSelectedRecurring([item.entryId]);
    await ensureRecurringTasksForToday();
    const tasks = await getTodayAutoTasks();
    expect(tasks[0].title).toBe(item.actionLabel);
  });
});
